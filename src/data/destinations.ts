export function getDestinationById(id: string): Destination | undefined {
  return DESTINATIONS.find((d) => d.id === id)
}

export function findDestinationByLabel(label: string): Destination | undefined {
  const normalized = label.toLowerCase().normalize('NFD').replace(/\p{Diacritic}/gu, '')
  return DESTINATIONS.find((d) => {
    const city = d.city.toLowerCase().normalize('NFD').replace(/\p{Diacritic}/gu, '')
    const country = d.country.toLowerCase().normalize('NFD').replace(/\p{Diacritic}/gu, '')
    return normalized.includes(city) || normalized.includes(country) || city.includes(normalized) || country.includes(normalized)
  })
}
